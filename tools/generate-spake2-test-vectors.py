#!/usr/bin/env python3
"""Independent slow affine Edwards25519 oracle. Test-only; not constant-time.

Uses public AOSP/BoringSSL SPAKE2 seed names and transcript convention.
All inputs are fixed synthetic test data, never live keys or pairing codes.
"""
import hashlib
from pathlib import Path

P = 2**255 - 19
L = 2**252 + 27742317777372353535851937790883648493
D = (-121665 * pow(121666, P - 2, P)) % P

def decode(data):
    encoded = int.from_bytes(data, 'little')
    y = encoded & (2**255 - 1)
    x2 = (y*y - 1) * pow(D*y*y + 1, P - 2, P) % P
    x = pow(x2, (P + 3)//8, P)
    if x*x % P != x2:
        x = x * pow(2, (P - 1)//4, P) % P
    assert x*x % P == x2
    if (x & 1) != (encoded >> 255):
        x = P-x
    return x, y

def encode(point):
    x, y = point
    return (y | ((x & 1) << 255)).to_bytes(32, 'little')

def add(a, b):
    x, y = a; u, v = b
    t = D*x*u*y*v % P
    return ((x*v + y*u)*pow(1+t, P-2, P) % P,
            (y*v + x*u)*pow(1-t, P-2, P) % P)

def mul(p, scalar):
    out = (0, 1)
    while scalar:
        if scalar & 1:
            out = add(out, p)
        p = add(p, p)
        scalar >>= 1
    return out

B = decode(bytes.fromhex('5866666666666666666666666666666666666666666666666666666666666666'))
M = decode(hashlib.sha256(b'edwards25519 point generation seed (M)').digest())
N = decode(hashlib.sha256(b'edwards25519 point generation seed (N)').digest())

def prefix(v):
    return len(v).to_bytes(8, 'little') + v

lines = ['# Generated by tools/generate-spake2-test-vectors.py; synthetic test material only.']
for n in range(4):
    a_seed = hashlib.sha512(('independent alice test %d' % n).encode()).digest()
    b_seed = hashlib.sha512(('independent bob test %d' % n).encode()).digest()
    password = hashlib.sha512(('independent password %d' % n).encode()).digest()
    a = (int.from_bytes(a_seed, 'little') % L) * 8
    b = (int.from_bytes(b_seed, 'little') % L) * 8
    ph = hashlib.sha512(password).digest()
    w = int.from_bytes(ph, 'little') % L
    while w % 8:
        w += L
    am = encode(add(mul(B, a), mul(M, w)))
    bm = encode(add(mul(B, b), mul(N, w)))
    shared = encode(mul(B, a*b))
    transcript = b''.join(map(prefix, [b'adb pair client\0', b'adb pair server\0', am, bm, shared, ph]))
    key = hashlib.sha512(transcript).digest()
    for field, value in [('a_seed',a_seed),('b_seed',b_seed),('password',password),('a_msg',am),('b_msg',bm),('key',key)]:
        lines.append('%d.%s=%s' % (n,field,value.hex()))
target = Path(__file__).resolve().parents[1] / 'core/src/test/resources/spake2-vectors.properties'
target.parent.mkdir(parents=True, exist_ok=True)
target.write_text('\n'.join(lines) + '\n')
print('Wrote 4 independent SPAKE2 test vectors')
